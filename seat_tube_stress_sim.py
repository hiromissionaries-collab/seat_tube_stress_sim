def smoothstep(x):
    x = min(max(x, 0.0), 1.0)
    return x * x * (3.0 - 2.0 * x)


def wrap_pi(x):
    return (x + math.pi) % (2.0 * math.pi) - math.pi


def cumtrapz0(y, dx):
    out = np.zeros_like(y)
    out[1:] = np.cumsum(0.5 * (y[1:] + y[:-1]) * dx)
    return out


def geometry_link(L, d, beta_deg):
    """幾何パラメータの自動連動:
         L_free = L - d             (有効露出長)
         h      = L_free · sin β    (支点高さ)
    L_free と h を返す。静力学 (statics) の h にこの値がそのまま入る。"""
    L_free = float(L) - float(d)
    h = L_free * math.sin(math.radians(beta_deg))
    return L_free, h


def h_is_auto(sim):
    """sim の h が L_free·sinβ (自動連動値) と一致していれば True。"""
    return abs(sim["h"] - sim["L_free"] * math.sin(math.radians(sim["beta"]))) < 1e-6


def statics(L, d, h, s, beta_deg, P):
    b = math.radians(beta_deg)
    cb, sb = math.cos(b), math.sin(b)
    arm = h * cb + s * sb                 # 荷重線とリム支点の水平距離 [mm]
    M_rim = P * arm                        # [N·mm]
    R2 = M_rim / d                         # 最下端・前壁側
    R1 = R2 + P * cb                       # リム端面・後壁側
    return dict(arm=arm, M_rim=M_rim, R1=R1, R2=R2, cb=cb, sb=sb)


def closure(phi, ramp, geo, mat):
    """φ(3,NTH,nz) -> (σr, σθ, σz, τθz)"""
    nu = mat["nu"]
    sr = LAM_R[:, None, None] * phi
    st = LAM_T[:, None, None] * phi
    sz = nu * (sr + st)
    Mb = ramp * geo["Mb"]
    Nax = ramp * geo["Nax"]
    sz = (sz + RD[:, None, None] * COS1[None, :, None] * Mb[None, None, :] / I_SEC
          - Nax[None, None, :] / AREA)
    # 軸方向つり合い:  (1/r) ∂τθz/∂θ = -∂σz/∂z
    dsz = np.gradient(sz, geo["dz"], axis=2)
    f = dsz - dsz.mean(axis=1, keepdims=True)
    cum = (np.cumsum(f, axis=1) - 0.5 * f) * DTH
    tau = -RD[:, None, None] * cum
    tau -= tau.mean(axis=1, keepdims=True)
    return sr, st, sz, tau


def vonmises(sr, st, sz, tau):
    return np.sqrt(0.5 * ((sr - st) ** 2 + (st - sz) ** 2 + (sz - sr) ** 2) + 3.0 * tau ** 2)


def curvature(eps_z):
    return np.einsum("j,jkz,k->z", WJ * RD ** 2, eps_z, COS1) * DTH / I_SEC



def _neumann_roots(m, nroots):
    """J_m'(λRo)Y_m'(λRi) - Y_m'(λRo)J_m'(λRi) = 0 の正根を小さい順に nroots 個返す。"""
    if m == 0:
        # J_0' = -J_1, Y_0' = -Y_1
        def f(lam):
            return sp.jv(1, lam * RO) * sp.yv(1, lam * RI) - sp.yv(1, lam * RO) * sp.jv(1, lam * RI)
        lo = 0.05
    else:
        def f(lam):
            return (sp.jvp(m, lam * RO) * sp.yvp(m, lam * RI)
                    - sp.yvp(m, lam * RO) * sp.jvp(m, lam * RI))
        lo = 0.3 * m / RO          # Rayleigh 商から λ >= m/Ro が保証される
    hi = m / RM + (nroots + 2) * math.pi / TW + 1.0
    while True:
        grid = np.arange(lo, hi, 0.002)
        vals = f(grid)
        idx = np.where(np.sign(vals[:-1]) * np.sign(vals[1:]) < 0)[0]
        if len(idx) >= nroots:
            break
        hi *= 1.5
    return [brentq(f, grid[i], grid[i + 1], xtol=1e-13, rtol=1e-13) for i in idx[:nroots]]


def _radial_function(m, lam, r):
    if lam == 0.0:
        return np.ones_like(r)
    return sp.jv(m, lam * r) * sp.yvp(m, lam * RI) - sp.yv(m, lam * r) * sp.jvp(m, lam * RI)


def build_basis():
    xq, wq = np.polynomial.legendre.leggauss(NRQ)
    rq = 0.5 * (RO - RI) * xq + 0.5 * (RO + RI)
    wq = 0.5 * (RO - RI) * wq
    lam = np.zeros((NM, NRAD))
    Rq = np.zeros((NM, NRAD, NRQ))
    Rd = np.zeros((NM, NRAD, 3))
    for m in range(NM):
        if m == 0:
            roots = [0.0] + _neumann_roots(0, NRAD - 1)
        else:
            roots = _neumann_roots(m, NRAD)
        for n, l in enumerate(roots):
            lam[m, n] = l
            norm = math.sqrt(np.sum(wq * rq * _radial_function(m, l, rq) ** 2))
            sign = 1.0 if _radial_function(m, l, np.array([RI]))[0] >= 0 else -1.0
            Rq[m, n] = sign * _radial_function(m, l, rq) / norm
            Rd[m, n] = sign * _radial_function(m, l, RD) / norm
    Pq = Rq * (wq * rq)[None, None, :]            # 射影 (重み r で正規直交)
    cosm = np.cos(np.outer(np.arange(NM), TH))    # (NM, NTH)
    fac = np.full(NM, 2.0 / NTH)
    fac[0] = 1.0 / NTH
    cproj = cosm * fac[:, None]
    return dict(lam=lam, Rq=Rq, Rd=Rd, Pq=Pq, rq=rq, wq=wq, cos=cosm, cproj=cproj)



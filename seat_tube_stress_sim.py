# 軸方向の輸送・拡散演算子 (半離散化 + 行列指数関数 -> 時間方向は厳密)
# ----------------------------------------------------------------------------
@lru_cache(maxsize=24)
def z_operator(nz, dz, Dz, v0):
    """未知数: z_1..z_{nz-1}。 z_0 = 0 (ディリクレ) / z_L ではミラーゴースト(ノイマン)。
    ∂tφ = Dz φ_zz + v0 φ_z  (ドリフトは z 減少方向, 中心差分; Pe <= 1 を呼び出し側で保証)"""
    nu_ = nz - 1
    D = Dz / dz ** 2
    a = v0 / (2.0 * dz)
    A = np.zeros((nu_, nu_))
    for i in range(nu_):
        A[i, i] = -2.0 * D
        if i > 0:
            A[i, i - 1] = D - a
        if i < nu_ - 1:
            A[i, i + 1] = D + a
    A[-1, -2] = 2.0 * D
    # 半離散系 dφ/dt = A φ の 1 サブステップ厳密伝播演算子 exp(dt A)
    # (固有分解は非正規行列で不安定になり得るため、スケーリング&スクエアリング法の expm を使う)
    return expm((DT_FRAME / SUBSTEPS) * A)



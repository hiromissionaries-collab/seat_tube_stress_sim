def _free_port(start=8050, tries=60):
    """使用中でない最初のポートを返す (Colab 等で前回のサーバーが残っていても起動できる)。"""
    import socket
    for p in range(start, start + tries):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sk:
            if sk.connect_ex(("127.0.0.1", p)) != 0:
                return p
    return start



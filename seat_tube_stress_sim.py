def compute_update(L, d, beta, P, s, Dz, Dp, v0, mat, h_in=None, h_auto=True):
    d_eff = float(min(d, L - 20.0))
    # 幾何の自動連動: L_free = L - d,  h = L_free sin β  (静力学の h・arm に自動反映)
    # h_auto=False のときは手動指定の h_in を使う
    L_free, h = geometry_link(L, d_eff, beta)
    if (not h_auto) and h_in is not None:
        h = float(h_in)
    sim = get_sim(L, d_eff, h, s, beta, P, mat, Dz, Dp, v0)
    page = build_viewer_html(sim, T0_DEFAULT)
    lines = stats_text(sim, NT, "plastic")[:5]
    lines.append(f"有効 D_z = {sim['Dz_eff']:.1f} mm²/s (セル Péclet 数 ≤ 1 を保証)")
    if d_eff < d:
        lines.append(f"※ 差し込み深さ d を L-20 = {d_eff:.0f} mm に制限しました。")
    return page, "\n".join(lines), build_derivation(sim)


def create_app():
    app = dash.Dash(__name__, title="シートパイプ応力拡散シミュレーター")
    app.layout = make_layout()

    @app.callback(Output("viewer", "srcDoc"), Output("stats", "children"),
                  Output("deriv-md", "children"),
                  Input("sl-L", "value"), Input("sl-d", "value"),
                  Input("sl-beta", "value"), Input("sl-P", "value"), Input("sl-s", "value"),
                  Input("sl-Dz", "value"), Input("sl-Dp", "value"), Input("sl-v", "value"),
                  Input("dd-mat", "value"), Input("sl-h", "value"), Input("ck-hauto", "value"))
    def update(L, d, beta, P, s, Dz, Dp, v0, mat, h_in, hauto):
        auto = bool(hauto) and "auto" in hauto
        # 自動連動中に sync_h が h スライダーを書き換えただけの発火では再計算しない
        if auto and dash.callback_context.triggered_id == "sl-h":
            raise dash.exceptions.PreventUpdate
        return compute_update(L, d, beta, P, s, Dz, Dp, v0, mat, h_in, auto)

    @app.callback(Output("sl-h", "value"), Output("h-wrap", "style"),
                  Input("sl-L", "value"), Input("sl-d", "value"), Input("sl-beta", "value"),
                  Input("ck-hauto", "value"))
    def sync_h(L, d, beta, hauto):
        if hauto and "auto" in hauto:
            _, h = geometry_link(L, min(d, L - 20.0), beta)
            return int(round(h)), {"opacity": 0.5, "pointerEvents": "none"}
        return dash.no_update, {}

    return app


app = create_app()
